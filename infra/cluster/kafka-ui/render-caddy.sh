#!/usr/bin/env bash
# Runs on the trainer VM (as root): reads "user,password" lines on stdin and writes the Caddy site
# /etc/caddy/kafka-ui.caddy for Kafka UI - basic auth for every user, learners limited to their own
# Kafka UI cluster (named after the user), trainer unrestricted. Called by scripts/deploy-kafka-ui.sh.
set -euo pipefail
FQDN=$1
minor=$(caddy version | sed -E 's/^v2\.([0-9]+).*/\1/'); [ "$minor" -ge 8 ] && BA=basic_auth || BA=basicauth
users=(); hashes=()
while IFS=, read -r u p || [ -n "$u" ]; do
  [ -z "$u" ] && continue
  users+=("$u"); hashes+=("$(printf '%s\n' "$p" | caddy hash-password)")
done

{
  echo "# Generated by infra/cluster/scripts/deploy-kafka-ui.sh - do not edit"
  echo "$FQDN {"
  echo "	log {"
  echo "		output file /var/log/caddy/kafka-ui.access.log"
  echo "	}"
  echo "	route {"
  echo "		$BA {"
  for i in "${!users[@]}"; do echo "			${users[$i]} ${hashes[$i]}"; done
  echo "		}"
  cat <<'STATIC'
		# Learners land on their own cluster and cannot reach config/actuator endpoints
		@learner_home {
			path /
			not expression `{http.auth.user.id} == "trainer"`
		}
		redir @learner_home /ui/clusters/{http.auth.user.id}/all-topics 302
		@admin_only {
			path /api/config /api/config/* /actuator /actuator/*
			not expression `{http.auth.user.id} == "trainer"`
		}
		respond @admin_only 403
STATIC
  for u in "${users[@]}"; do
    [ "$u" = trainer ] && continue
    cat <<USER
		@deny_$u {
			expression \`{http.auth.user.id} == "$u"\`
			path /ui/clusters/* /api/clusters/*
			not path /ui/clusters/$u /ui/clusters/$u/* /api/clusters/$u /api/clusters/$u/*
		}
		respond @deny_$u 403
		# Cluster Describe makes ListGroups return every learner's groups and v0.7.2 fails the whole
		# page on the first one it may not describe; its search filter runs before describe.
		@groups_$u {
			expression \`{http.auth.user.id} == "$u"\`
			path /api/clusters/$u/consumer-groups/paged
		}
		uri @groups_$u query search $u.
USER
  done
  echo "		reverse_proxy 127.0.0.1:18080"
  echo "	}"
  echo "}"
} > /etc/caddy/kafka-ui.caddy.new
chgrp caddy /etc/caddy/kafka-ui.caddy.new; chmod 640 /etc/caddy/kafka-ui.caddy.new
mv /etc/caddy/kafka-ui.caddy.new /etc/caddy/kafka-ui.caddy
grep -qx 'import /etc/caddy/kafka-ui.caddy' /etc/caddy/Caddyfile || printf '\nimport /etc/caddy/kafka-ui.caddy\n' >> /etc/caddy/Caddyfile
# validate runs as root and would create the access log root-owned, which the caddy service can't open
touch /var/log/caddy/kafka-ui.access.log; chown caddy:caddy /var/log/caddy/kafka-ui.access.log; chmod 640 /var/log/caddy/kafka-ui.access.log
caddy validate --adapter caddyfile --config /etc/caddy/Caddyfile >/dev/null
systemctl reload caddy
echo "caddy reloaded"
