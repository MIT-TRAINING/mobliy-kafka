#!/usr/bin/env bash
# Publishes Control Center (cp-services.lab.internal:9021, private) at https://c3.kafka.supercloudlabs.com
# through the trainer VM's Caddy, the same way as Kafka UI (infra/cluster/kafka-ui/README.md):
#   1. Route 53 A record  c3.kafka.supercloudlabs.com -> trainer VM Elastic IP (not in Terraform)
#   2. /etc/caddy/cp-ca.pem       the course CA, so Caddy trusts Control Center's certificate
#   3. /etc/caddy/c3.caddy        site block (Let's Encrypt), imported from /etc/caddy/Caddyfile
# Control Center does its own LDAP login, so Caddy adds no authentication. Idempotent.
# Runs from the admin laptop (SSH to the trainer VM is open to the admin IPs only).
# Usage: publish-control-center.sh [fqdn]
set -euo pipefail
HERE="$(cd "$(dirname "$0")/.." && pwd)"
INFRA="$(cd "$HERE/.." && pwd)"
FQDN=${1:-c3.kafka.supercloudlabs.com}
ZONE=${FQDN#*.}
PEM="$INFRA/secrets/kafka-lab-admin.pem"
CA="$HERE/secrets/certs/ca.pem"
AWS=(aws --profile "${AWS_PROFILE:-kafka-training}" --region "${AWS_REGION:-ap-south-1}")

IP=$(terraform -chdir="$INFRA/terraform" output -json vms | jq -r '.trainer.public_ip')
SSH=(ssh -i "$PEM" -o StrictHostKeyChecking=no -o UserKnownHostsFile=/dev/null -o LogLevel=ERROR -o ConnectTimeout=8 -o BatchMode=yes "ubuntu@$IP")

echo "== DNS $FQDN -> $IP"
ZID=$("${AWS[@]}" route53 list-hosted-zones-by-name --dns-name "$ZONE" --query 'HostedZones[0].Id' --output text)
"${AWS[@]}" route53 change-resource-record-sets --hosted-zone-id "$ZID" --change-batch "$(jq -n --arg n "$FQDN" --arg ip "$IP" \
  '{Changes:[{Action:"UPSERT",ResourceRecordSet:{Name:$n,Type:"A",TTL:60,ResourceRecords:[{Value:$ip}]}}]}')" \
  --query ChangeInfo.Id --output text | xargs "${AWS[@]}" route53 wait resource-record-sets-changed --id

echo "== Caddy site $FQDN -> https://cp-services.lab.internal:9021"
"${SSH[@]}" 'sudo install -m 644 /dev/stdin /etc/caddy/cp-ca.pem' < "$CA"
"${SSH[@]}" 'sudo tee /etc/caddy/c3.caddy >/dev/null' <<EOF
# Generated by infra/confluent/scripts/publish-control-center.sh - do not edit
$FQDN {
	log {
		output file /var/log/caddy/c3.access.log
	}
	reverse_proxy https://cp-services.lab.internal:9021 {
		transport http {
			tls_trust_pool file /etc/caddy/cp-ca.pem
			tls_server_name cp-services.lab.internal
		}
	}
}
EOF
"${SSH[@]}" 'grep -qxF "import /etc/caddy/c3.caddy" /etc/caddy/Caddyfile || echo "import /etc/caddy/c3.caddy" | sudo tee -a /etc/caddy/Caddyfile >/dev/null
sudo caddy validate --config /etc/caddy/Caddyfile --adapter caddyfile >/dev/null 2>&1
# validate runs as root and creates the access log; the caddy service user must own it
sudo install -o caddy -g caddy -m 640 /dev/null /var/log/caddy/c3.access.log
sudo systemctl reload caddy'

echo "== waiting for the Let's Encrypt certificate"
for _ in $(seq 1 24); do
  code=$(curl -s -o /dev/null -w '%{http_code}' --max-time 10 "https://$FQDN/" || true)
  [[ "$code" =~ ^(200|30[0-9])$ ]] && { echo "== done: https://$FQDN (HTTP $code; log in with an LDAP user)"; exit 0; }
  sleep 5
done
echo "!! https://$FQDN not answering yet; check: ssh ubuntu@$IP 'journalctl -u caddy -n 50'"; exit 1
